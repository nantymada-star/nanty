export type MsgKey = keyof typeof M
const IDX: Record<Lang, 0 | 1> = { mg: 0, fr: 1 }

export function translate(lang: Lang, key: MsgKey, vars?: Record<string, string | number>) {
  let s: string = M[key][IDX[lang]]
  if (vars) for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v))
  return s
}

export function useT() {
  const { lang } = useSettings()
  const t = useCallback((key: MsgKey, vars?: Record<string, string | number>) => translate(lang, key, vars), [lang])
  return { t, lang }
}

